CREATE UNIQUE INDEX IF NOT EXISTS bookings_user_idempotency_key_idx
    ON bookings (user_id, idempotency_key)
    WHERE idempotency_key IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS bookings_qr_identifier_idx
    ON bookings (qr_identifier)
    WHERE qr_identifier IS NOT NULL;

CREATE TABLE IF NOT EXISTS muscle_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE IF NOT EXISTS exercises (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE IF NOT EXISTS exercise_muscle_groups (
    exercise_id BIGINT NOT NULL REFERENCES exercises (id) ON DELETE CASCADE,
    muscle_group_id BIGINT NOT NULL REFERENCES muscle_groups (id) ON DELETE CASCADE,
    role VARCHAR(20) NOT NULL CHECK (role IN ('PRIMARY', 'SECONDARY')),
    PRIMARY KEY (exercise_id, muscle_group_id)
);

CREATE INDEX IF NOT EXISTS exercise_muscle_groups_muscle_group_idx
    ON exercise_muscle_groups (muscle_group_id, exercise_id);

CREATE TABLE IF NOT EXISTS workout_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    duration_min INTEGER NOT NULL CHECK (duration_min BETWEEN 1 AND 480),
    notes TEXT,
    UNIQUE (user_id, started_at)
);

CREATE TABLE IF NOT EXISTS workout_exercises (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workout_id BIGINT NOT NULL REFERENCES workout_sessions (id) ON DELETE CASCADE,
    exercise_id BIGINT NOT NULL REFERENCES exercises (id),
    sets_count INTEGER NOT NULL CHECK (sets_count BETWEEN 1 AND 30),
    reps_per_set INTEGER NOT NULL CHECK (reps_per_set BETWEEN 1 AND 200),
    weight_kg NUMERIC(7, 2) CHECK (weight_kg IS NULL OR weight_kg >= 0),
    UNIQUE (workout_id, exercise_id)
);

CREATE INDEX IF NOT EXISTS workout_exercises_exercise_idx
    ON workout_exercises (exercise_id, workout_id);
